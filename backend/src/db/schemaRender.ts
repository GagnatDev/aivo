import type { TableMetadata } from "kysely";

// Pure renderer behind `pnpm db:codegen` (see codegen.ts): turns Kysely's introspected
// table metadata into the source of `db/schema.ts`. Kept free of I/O so it is unit-tested
// without a database; codegen.ts owns the connection and the write/verify step.

/**
 * Postgres `typname` → TypeScript type. A column whose type is missing here (and has no
 * override) fails codegen, so a new column type is mapped deliberately rather than
 * silently widened. `numeric` stays a string: node-pg returns it as one to preserve
 * precision (the money convention, see docs/data-model.md).
 */
export const SCALAR_TYPES: Readonly<Record<string, string>> = {
  bool: "boolean",
  date: "Timestamp",
  float4: "number",
  float8: "number",
  int2: "number",
  int4: "number",
  numeric: "Numeric",
  text: "string",
  timestamptz: "Timestamp",
  uuid: "string",
  varchar: "string",
};

// Helper aliases, emitted (in this order) only when a column uses them.
const HELPER_TYPES: Readonly<Record<string, string>> = {
  Generated: `export type Generated<T> = T extends ColumnType<infer S, infer I, infer U>
  ? ColumnType<S, I | undefined, U>
  : ColumnType<T, T | undefined, T>;`,
  Numeric: "export type Numeric = ColumnType<string, number | string, number | string>;",
  Timestamp: "export type Timestamp = ColumnType<Date, Date | string, Date | string>;",
};

export interface RenderOptions {
  /** `table.column` → TS type expression, emitted verbatim (no `| null` / `Generated<>` added). */
  overrides: Readonly<Record<string, string>>;
  /** Type name referenced by an override → module it is imported from. */
  customImports: Readonly<Record<string, string>>;
}

const HEADER = `/**
 * This file was generated by \`pnpm db:codegen\` (src/db/codegen.ts).
 * Please do not edit it manually.
 */`;

const pascalCase = (name: string): string =>
  name
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** Render `db/schema.ts` for the given tables. Throws on a column type with no mapping. */
export function renderSchema(tables: readonly TableMetadata[], options: RenderOptions): string {
  const usedHelpers = new Set<string>();
  const usedOverrides: string[] = [];

  const columnType = (table: string, column: TableMetadata["columns"][number]): string => {
    const override = options.overrides[`${table}.${column.name}`];
    if (override !== undefined) {
      usedOverrides.push(override);
      return override;
    }
    const scalar = SCALAR_TYPES[column.dataType];
    if (scalar === undefined) {
      throw new Error(
        `No TypeScript mapping for ${table}.${column.name} (Postgres type "${column.dataType}"): add it to SCALAR_TYPES or an override in codegen.ts.`,
      );
    }
    if (scalar in HELPER_TYPES) usedHelpers.add(scalar);
    const type = column.isNullable ? `${scalar} | null` : scalar;
    if (!column.hasDefaultValue && !column.isAutoIncrementing) return type;
    usedHelpers.add("Generated");
    return `Generated<${type}>`;
  };

  const sorted = [...tables].sort((a, b) => compare(pascalCase(a.name), pascalCase(b.name)));
  const interfaces = sorted.map((table) => {
    const columns = [...table.columns]
      .sort((a, b) => compare(a.name, b.name))
      .map((column) => `  ${column.name}: ${columnType(table.name, column)};`);
    return `export interface ${pascalCase(table.name)} {\n${columns.join("\n")}\n}`;
  });
  const dbEntries = [...tables]
    .sort((a, b) => compare(a.name, b.name))
    .map((table) => `  ${table.name}: ${pascalCase(table.name)};`);
  const helpers = Object.keys(HELPER_TYPES).filter((name) => usedHelpers.has(name));

  return `${[
    HEADER,
    renderImports(usedOverrides, options.customImports, helpers.length > 0),
    ...helpers.map((name) => HELPER_TYPES[name]),
    ...interfaces,
    `export interface DB {\n${dbEntries.join("\n")}\n}`,
  ]
    .filter((section) => section !== "")
    .join("\n\n")}\n`;
}

/** Import the custom types the used overrides reference, then `ColumnType` if anything needs it. */
function renderImports(
  usedOverrides: readonly string[],
  customImports: RenderOptions["customImports"],
  helpersEmitted: boolean,
): string {
  const identifiers = new Set(usedOverrides.flatMap((o) => o.match(/[A-Za-z_$][\w$]*/g) ?? []));
  const byModule = new Map<string, string[]>();
  for (const [name, module] of Object.entries(customImports)) {
    if (identifiers.has(name)) byModule.set(module, [...(byModule.get(module) ?? []), name]);
  }
  const lines = [...byModule.entries()]
    .sort(([a], [b]) => compare(a, b))
    .map(
      ([module, names]) => `import type { ${names.sort(compare).join(", ")} } from "${module}";`,
    );
  if (helpersEmitted || identifiers.has("ColumnType")) {
    lines.push(`import type { ColumnType } from "kysely";`);
  }
  return lines.join("\n");
}
