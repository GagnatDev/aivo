import { logger } from "../logger.js";
import { tokenRefreshError, YoutubeApiError } from "./errors.js";

/**
 * Port + implementation for the YouTube Data API v3 (subscriptions-only, per
 * docs/concept.md). All calls authenticate as the single owner-connected account via
 * an OAuth refresh token (subscriptions.list requires `mine=true`); the refresh token
 * comes from the deployment secrets, never the database. The pipeline talks to the
 * {@link YoutubeApi} port so tests substitute a fake — nothing here is unit-tested
 * against the network except the pure helpers.
 */

export interface SubscribedChannel {
  id: string;
  title: string;
  thumbnailUrl: string | null;
}

export interface DiscoveredVideo {
  id: string;
  channelId: string;
  title: string;
  description: string;
  publishedAt: Date;
  thumbnailUrl: string | null;
  durationSeconds: number | null;
}

export interface YoutubeApi {
  /** The connected account's full current subscription list. */
  listSubscriptions(): Promise<SubscribedChannel[]>;
  /** New uploads on the given channels since `since` (metadata incl. duration). */
  listNewVideos(channelIds: string[], since: Date): Promise<DiscoveredVideo[]>;
}

export interface YoutubeOauthConfig {
  clientId: string;
  clientSecret: string;
  refreshToken: string;
}

const API_BASE = "https://www.googleapis.com/youtube/v3";
const TOKEN_URL = "https://oauth2.googleapis.com/token";
// Recent uploads fetched per channel poll — bounds quota; a channel uploading more
// than this between digests only contributes its newest uploads.
const UPLOADS_PER_CHANNEL = 10;
// Refresh the access token a minute early so an in-flight batch never expires mid-run.
const TOKEN_SLACK_MS = 60_000;

/**
 * Parse an ISO-8601 duration ("PT1H2M3S") to seconds; null for missing/unparsable
 * input (e.g. live streams report "P0D").
 */
export function parseIso8601Duration(input: string | undefined): number | null {
  if (!input) return null;
  const match = /^P(?:(\d+)D)?(?:T(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?)?$/.exec(input);
  if (!match) return null;
  const [, days, hours, minutes, seconds] = match.map((v) => (v ? Number(v) : 0));
  const total = days * 86_400 + hours * 3_600 + minutes * 60 + seconds;
  return total > 0 ? total : null;
}

/**
 * A channel's "uploads" playlist id: channel ids are `UC…`, the autogenerated uploads
 * playlist is the same id with a `UU` prefix. Saves a channels.list call per channel.
 */
export function uploadsPlaylistId(channelId: string): string {
  return channelId.startsWith("UC") ? `UU${channelId.slice(2)}` : channelId;
}

interface TokenState {
  accessToken: string;
  expiresAt: number;
}

/** The real Data API client. Quota-aware: playlistItems + batched videos.list only. */
export function createYoutubeDataApi(cfg: YoutubeOauthConfig): YoutubeApi {
  let token: TokenState | undefined;

  async function accessToken(): Promise<string> {
    if (token && token.expiresAt - TOKEN_SLACK_MS > Date.now()) return token.accessToken;
    const res = await fetch(TOKEN_URL, {
      method: "POST",
      headers: { "content-type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({
        client_id: cfg.clientId,
        client_secret: cfg.clientSecret,
        refresh_token: cfg.refreshToken,
        grant_type: "refresh_token",
      }),
    });
    if (!res.ok) {
      // Typed so the digest pipeline can tell "the owner must re-authorize" apart from
      // "Google's token endpoint is having a bad day" (youtube/errors.ts).
      throw tokenRefreshError(res.status, await res.text());
    }
    const body = (await res.json()) as { access_token: string; expires_in: number };
    token = { accessToken: body.access_token, expiresAt: Date.now() + body.expires_in * 1000 };
    return token.accessToken;
  }

  async function get(path: string, params: Record<string, string>): Promise<unknown> {
    const url = new URL(`${API_BASE}/${path}`);
    for (const [k, v] of Object.entries(params)) url.searchParams.set(k, v);
    const res = await fetch(url, {
      headers: { authorization: `Bearer ${await accessToken()}` },
    });
    if (!res.ok) {
      // A 401/403 here means the access token we just minted was rejected (scope revoked
      // mid-flight); everything else is the Data API erroring.
      throw new YoutubeApiError(
        res.status === 401 || res.status === 403 ? "auth" : "api",
        `YouTube API ${path} failed: ${res.status} ${(await res.text()).slice(0, 200).trim()}`,
        { status: res.status },
      );
    }
    return res.json();
  }

  return {
    async listSubscriptions(): Promise<SubscribedChannel[]> {
      const channels: SubscribedChannel[] = [];
      let pageToken: string | undefined;
      do {
        const page = (await get("subscriptions", {
          part: "snippet",
          mine: "true",
          maxResults: "50",
          ...(pageToken ? { pageToken } : {}),
        })) as {
          nextPageToken?: string;
          items?: Array<{
            snippet?: {
              title?: string;
              resourceId?: { channelId?: string };
              thumbnails?: { default?: { url?: string } };
            };
          }>;
        };
        for (const item of page.items ?? []) {
          const id = item.snippet?.resourceId?.channelId;
          if (!id) continue;
          channels.push({
            id,
            title: item.snippet?.title ?? id,
            thumbnailUrl: item.snippet?.thumbnails?.default?.url ?? null,
          });
        }
        pageToken = page.nextPageToken;
      } while (pageToken);
      return channels;
    },

    async listNewVideos(channelIds: string[], since: Date): Promise<DiscoveredVideo[]> {
      // Pass 1: each channel's uploads playlist (1 quota unit per channel) for ids +
      // snippets newer than the watermark.
      const found: Omit<DiscoveredVideo, "durationSeconds">[] = [];
      for (const channelId of channelIds) {
        let page: unknown;
        try {
          page = await get("playlistItems", {
            part: "snippet,contentDetails",
            playlistId: uploadsPlaylistId(channelId),
            maxResults: String(UPLOADS_PER_CHANNEL),
          });
        } catch (err) {
          // A channel with zero uploads 404s; anything else is worth a log but must
          // not sink the whole poll.
          logger.warn({ err, channelId }, "youtube uploads poll failed for channel");
          continue;
        }
        const items = (
          page as {
            items?: Array<{
              snippet?: {
                title?: string;
                description?: string;
                resourceId?: { videoId?: string };
                thumbnails?: { medium?: { url?: string }; default?: { url?: string } };
              };
              contentDetails?: { videoId?: string; videoPublishedAt?: string };
            }>;
          }
        ).items;
        for (const item of items ?? []) {
          const id = item.contentDetails?.videoId ?? item.snippet?.resourceId?.videoId;
          const publishedAt = item.contentDetails?.videoPublishedAt;
          if (!id || !publishedAt) continue;
          const published = new Date(publishedAt);
          if (published <= since) continue;
          found.push({
            id,
            channelId,
            title: item.snippet?.title ?? id,
            description: item.snippet?.description ?? "",
            publishedAt: published,
            thumbnailUrl:
              item.snippet?.thumbnails?.medium?.url ??
              item.snippet?.thumbnails?.default?.url ??
              null,
          });
        }
      }

      // Pass 2: durations in batches of 50 (1 quota unit per batch).
      const durations = new Map<string, number | null>();
      for (let i = 0; i < found.length; i += 50) {
        const batch = found.slice(i, i + 50);
        const page = (await get("videos", {
          part: "contentDetails",
          id: batch.map((v) => v.id).join(","),
        })) as { items?: Array<{ id?: string; contentDetails?: { duration?: string } }> };
        for (const item of page.items ?? []) {
          if (item.id) durations.set(item.id, parseIso8601Duration(item.contentDetails?.duration));
        }
      }
      return found.map((v) => ({ ...v, durationSeconds: durations.get(v.id) ?? null }));
    },
  };
}
